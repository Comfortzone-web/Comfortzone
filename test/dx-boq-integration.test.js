const test = require('node:test');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const os = require('node:os');
const path = require('node:path');
const net = require('node:net');
const { spawn } = require('node:child_process');
const DXBoq = require('../public/dx-boq');

test('DX BOQ uses existing Price List and quotation persistence, VAT, idempotence and access controls', async t => {
  const root = path.join(__dirname, '..'), directory = fs.mkdtempSync(path.join(os.tmpdir(), 'dx-boq-api-'));
  const probe = net.createServer(); await new Promise(resolve => probe.listen(0, '127.0.0.1', resolve));
  const port = probe.address().port; await new Promise(resolve => probe.close(resolve));
  fs.mkdirSync(path.join(directory, 'public'));
  fs.copyFileSync(path.join(root, 'public/dx-boq.js'), path.join(directory, 'public/dx-boq.js'));
  for (const file of ['project-progress.js','maintenance-api.js','maintenance-store.js','maintenance-billing.js','sales-quotation-pdf.js','dx-schedule-pdf.js']) fs.copyFileSync(path.join(root,file),path.join(directory,file));
  fs.writeFileSync(path.join(directory,'server.js'),fs.readFileSync(path.join(root,'server.js'),'utf8').replace('const PORTS = [5175, 5176, 5177, 8085];',`const PORTS = [${port}];`));
  const child=spawn(process.execPath,['server.js'],{cwd:directory,windowsHide:true,stdio:'ignore',env:{...process.env,NODE_PATH:path.join(root,'node_modules'),SUPABASE_URL:'',SUPABASE_KEY:'',VERCEL:''}});
  t.after(()=>child.kill());
  const base=`http://127.0.0.1:${port}`;
  let ready=false;
  for(let i=0;i<80;i++){try{await fetch(base+'/api/auth/me');ready=true;break;}catch{await new Promise(resolve=>setTimeout(resolve,100));}}
  assert.ok(ready,'isolated API starts');
  const login=await fetch(base+'/api/auth/login',{method:'POST',headers:{'Content-Type':'application/json'},body:JSON.stringify({email:'admin@comfortzone.local',password:'admin123'})});
  const cookie=login.headers.get('set-cookie').split(';')[0];
  async function api(url,body,method=body?'POST':'GET',session=cookie){
    const response=await fetch(base+url,{method,headers:{'Content-Type':'application/json',...(session?{Cookie:session}:{})},...(body?{body:JSON.stringify(body)}:{})});
    return {status:response.status,data:await response.json()};
  }
  assert.equal((await api('/api/costing',null,'GET','')).status,401);
  await api('/api/sales-crm/customers',{name:'DX Test Customer'});
  const priceResponse=await api('/api/costing/price-items',{model:'INDOOR / OUTDOOR',finalPrice:1000,description:'Test set'});
  assert.equal(priceResponse.status,200);
  const priceItems=priceResponse.data.priceItems;
  const draft=await api('/api/projects?draft=1',{workflowMode:'dx'});
  const project=draft.data;
  project.details.project='DX BOQ Project';project.details.customer='DX Test Customer';
  project.details.consultant='Consultant';project.details.contractor='Contractor';project.visible=true;
  project.tables.vrvSchedule.rows=[{'Model ( Indoor / Outdoor )':'INDOOR / OUTDOOR',Qty:2,Ref:'DX-01'}];
  project.dx={step:3,autosaveEnabled:true,boq:DXBoq.sync(null,project.tables.vrvSchedule.rows,priceItems)};
  const saved=await api('/api/projects/'+project.id,project,'PUT');assert.equal(saved.status,200);
  const init={fromDxBoq:true,sourceDxWorkflowId:project.id};
  const calls=await Promise.all([api('/api/sales-crm/quotations',init),api('/api/sales-crm/quotations',init)]);
  for(const call of calls)assert.equal(call.status,200,JSON.stringify(call.data));
  assert.equal(calls[0].data.savedItemId,calls[1].data.savedItemId);
  const quote=calls[1].data.quotations.find(q=>q.id===calls[1].data.savedItemId);
  assert.equal(calls[1].data.quotations.filter(q=>q.sourceDxWorkflowId===project.id).length,1);
  assert.equal(quote.status,'Draft');assert.equal(quote.items[0].qty,2);assert.equal(quote.items[0].unitPrice,1250);
  assert.equal(quote.amount,2625);assert.equal(quote.items[0].unitCost,1000);assert.equal(quote.dxPricing.percentage,20);
  assert.equal(quote.consultant,'Consultant');assert.equal(quote.contractor,'Contractor');assert.match(quote.dxSelectionNumber,/^DX-/);
  assert.deepEqual(quote.items[0].priceItemIds,[priceItems.find(item=>item.model==='INDOOR / OUTDOOR').id]);
  quote.items[0].qty=3;
  const update=await api('/api/sales-crm/quotations',quote);assert.equal(update.status,200);
  assert.equal(update.data.quotations.find(q=>q.id===quote.id).amount,3937.5);
  const repeat=await api('/api/sales-crm/quotations',init);assert.equal(repeat.data.quotations.find(q=>q.id===quote.id).items[0].qty,3,'reopen does not overwrite edited quotation');
  quote.terms='Preserved terms';quote.notes='Preserved notes';quote.discount=50;
  await api('/api/sales-crm/quotations',quote);
  project.tables.vrvSchedule.rows[0].Qty=4;
  project.dx.boq.margin=25;
  await api('/api/projects/'+project.id,project,'PUT');
  const modified=await api('/api/sales-crm/quotations',{...init,modifyDxBoq:true});
  assert.equal(modified.status,200);
  const revised=modified.data.quotations.find(q=>q.id===quote.id);
  assert.equal(revised.no,quote.no);assert.equal(revised.status,quote.status);
  assert.equal(revised.terms,'Preserved terms');assert.equal(revised.notes,'Preserved notes');assert.equal(revised.discount,50);
  assert.equal(revised.items[0].qty,4);assert.equal(revised.items[0].unitPrice,1333.33);
  assert.equal(revised.amount,5547.49);
  assert.equal(modified.data.quotations.filter(q=>q.sourceDxWorkflowId===project.id).length,1);
  // A new workflow with unresolved prices must never produce a draft.
  const missing=(await api('/api/projects?draft=1',{workflowMode:'dx'})).data;
  missing.details={...project.details};missing.visible=true;missing.tables.vrvSchedule.rows=[{'Model ( Indoor / Outdoor )':'UNKNOWN',Qty:1}];
  missing.dx={step:3,autosaveEnabled:true,boq:DXBoq.sync(null,missing.tables.vrvSchedule.rows,priceItems)};
  await api('/api/projects/'+missing.id,missing,'PUT');
  const rejected=await api('/api/sales-crm/quotations',{fromDxBoq:true,sourceDxWorkflowId:missing.id});assert.equal(rejected.status,422);assert.match(rejected.data.error,/Unit Price/);
  await api('/api/settings/users',{name:'PO Test',email:'po-test@example.test',password:'test-password',role:'POOnly'});
  const poLogin=await api('/api/auth/login',{email:'po-test@example.test',password:'test-password'});
  assert.equal(poLogin.status,200);
  const poResponse=await fetch(base+'/api/auth/login',{method:'POST',headers:{'Content-Type':'application/json'},body:JSON.stringify({email:'po-test@example.test',password:'test-password'})});
  const poCookie=poResponse.headers.get('set-cookie').split(';')[0];
  assert.equal((await api('/api/costing',null,'GET',poCookie)).status,403);
  assert.equal((await api('/api/sales-crm/quotations',init,'POST',poCookie)).status,403);
});
